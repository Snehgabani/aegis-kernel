#!/usr/bin/env node
/**
 * @file scripts/gen-homoglyph-maps.mjs
 * @description Unicode UTS #39 Confusables Multi-Language Code Generator.
 *
 * Reads `docs/HOMOGLYPH_MAP.json` and compiles synchronized lookup tables for:
 * - TypeScript: `packages/core/src/normalizers/homoglyphs.generated.ts`
 * - Python: `packages/python/aegis_kernel/homoglyphs_generated.py`
 *
 * Guarantees 100% de-obfuscation parity across all language runtimes.
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'fs';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);
const ROOT_DIR = join(__dirname, '..');

const MAP_PATH = join(ROOT_DIR, 'docs', 'HOMOGLYPH_MAP.json');

export function generateHomoglyphTables() {
  if (!existsSync(MAP_PATH)) {
    console.error(`❌ Could not find ${MAP_PATH}`);
    process.exit(1);
  }

  const raw = JSON.parse(readFileSync(MAP_PATH, 'utf-8'));
  const mappings = raw.mappings || {};
  const count = Object.keys(mappings).length;

  console.log(`🔨 Generating Unicode confusable tables across SDKs (${count} mappings)...`);

  // 1. Generate TypeScript Table
  const tsContent = `// @generated by scripts/gen-homoglyph-maps.mjs - DO NOT EDIT DIRECTLY
// Unicode UTS #39 Confusable Normalization Table (v${raw.meta?.version || '1.0.0'})

export const HOMOGLYPH_MAP: Record<string, string> = ${JSON.stringify(mappings, null, 2)};

export function normalizeHomoglyphs(text: string): string {
  let result = '';
  for (const char of text) {
    result += HOMOGLYPH_MAP[char] !== undefined ? HOMOGLYPH_MAP[char] : char;
  }
  return result;
}
`;
  const tsPath = join(ROOT_DIR, 'packages', 'core', 'src', 'normalizers', 'homoglyphs.generated.ts');
  mkdirSync(dirname(tsPath), { recursive: true });
  writeFileSync(tsPath, tsContent, 'utf-8');
  console.log(`   ✅ TypeScript table generated at ${tsPath}`);

  // 2. Generate Python Table
  const pyContent = `# @generated by scripts/gen-homoglyph-maps.mjs - DO NOT EDIT DIRECTLY
# Unicode UTS #39 Confusable Normalization Table (v${raw.meta?.version || '1.0.0'})

HOMOGLYPH_MAP = ${JSON.stringify(mappings, null, 4)}

def normalize_homoglyphs(text: str) -> str:
    return "".join(HOMOGLYPH_MAP.get(char, char) for char in text)
`;
  const pyPath = join(ROOT_DIR, 'packages', 'python', 'aegis_kernel', 'homoglyphs_generated.py');
  if (existsSync(dirname(pyPath))) {
    writeFileSync(pyPath, pyContent, 'utf-8');
    console.log(`   ✅ Python table generated at ${pyPath}`);
  }

  console.log('🎯 All multi-language homoglyph maps synchronized successfully.\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  generateHomoglyphTables();
}
